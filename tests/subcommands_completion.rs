// ── zsh ──────────────────────────────────────────────────────────

#[test]
fn zsh_script_has_compdef_header_and_parametrized_identifiers() {
    let fx = Fixture::real();
    let script = generate_zsh(&fx.registry(), "wrap");
    assert!(script.starts_with("#compdef wrap\n# Generated by `wrap --completion zsh`. Do not edit by hand.\n\n_wrap_providers() {\n"));
    assert!(script.contains("\n_wrap() {\n  _arguments -s \\\n    '"));
    assert!(script.ends_with("\n}\n\n_wrap \"$@\"\n"));
    let custom = generate_zsh(&fx.registry(), "foo");
    assert!(custom.starts_with("#compdef foo\n"));
    assert!(custom.contains("_foo()") && custom.contains("_foo_providers()"));
    assert!(custom.contains(":provider:_foo_providers") && custom.contains("_foo \"$@\""));
    assert!(!custom.contains("_wrap") && !custom.contains("#compdef wrap"));
}

#[test]
fn zsh_specs_cover_every_flag_alias_and_description() {
    let fx = Fixture::real();
    let script = generate_zsh(&fx.registry(), "wrap");
    for flag in fx.all() {
        assert!(
            script.contains(&format!("[{}]", flag.description)),
            "{}",
            flag.flag
        );
        let all = names(flag);
        if all.len() > 1 {
            let exclusion = format!("({})", all.join(" "));
            for name in &all {
                assert!(script.contains(&format!("'{exclusion}{name}")), "{name}");
            }
        } else {
            let re = regex::Regex::new(&format!("'{}[=\\[]", regex::escape(&flag.flag))).unwrap();
            assert!(re.is_match(&script), "{}", flag.flag);
        }
    }
    assert!(
        script.contains(
            "'(--help -h)--help[Show this help]' \\\n    '(--help -h)-h[Show this help]'"
        )
    );
}

