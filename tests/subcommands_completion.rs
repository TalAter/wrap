fn args(list: &[&str]) -> Vec<String> {
    list.iter().map(|a| a.to_string()).collect()
}

#[test]
fn run_completion_accepts_shell_and_optional_name() {
    let ok = run_completion(&args(&["zsh"])).unwrap();
    assert_eq!(
        (ok.shell, ok.executable_name.as_str()),
        (Shell::Zsh, "wrap")
    );
    let ok = run_completion(&args(&["bash", "myalias"])).unwrap();
    assert_eq!(
        (ok.shell, ok.executable_name.as_str()),
        (Shell::Bash, "myalias")
    );
    assert_eq!(run_completion(&args(&["fish"])).unwrap().shell, Shell::Fish);
}

#[test]
fn run_completion_rejects_bad_arguments_with_hints() {
    let hint = "Run `wrap --help completion` for install instructions.";
    assert_eq!(
        run_completion(&args(&[])).unwrap_err(),
        format!("--completion requires a shell name (zsh/bash/fish). {hint}")
    );
    assert!(
        run_completion(&args(&[""]))
            .unwrap_err()
            .contains("requires a shell name")
    );
    assert_eq!(
        run_completion(&args(&["zsh", "w", "extra"])).unwrap_err(),
        format!("--completion takes at most two arguments (shell and optional name). {hint}")
    );
    assert_eq!(
        run_completion(&args(&["powershell"])).unwrap_err(),
        format!("Unsupported shell: powershell. Supported: zsh, bash, fish. {hint}")
    );
    for bad in [
        "bad name",
        "1wrap",
        "my-wrap",
        "wräp",
        "wrap;rm",
        "wrap$(pwd)",
        "",
    ] {
        let err = run_completion(&args(&["zsh", bad])).unwrap_err();
        assert!(
            err.starts_with(&format!(
                "Invalid executable name \"{bad}\": the name is used as a shell function identifier"
            )),
            "{err}"
        );
        assert!(err.ends_with("so it must start with a letter or underscore and contain only letters, digits, and underscores."));
    }
}

#[test]
fn run_prints_script_to_stdout_or_error_to_chrome() {
    let mut out = Vec::new();
    let (code, chrome) = capture_chrome(|| completion::run(&args(&["zsh", "w"]), &mut out));
    assert_eq!(code, 0);
    assert!(chrome.is_empty());
    let text = String::from_utf8(out).unwrap();
    assert!(text.starts_with("#compdef w\n"));
    assert!(text.contains("_w()"));
    let mut out = Vec::new();
    let (code, chrome) = capture_chrome(|| completion::run(&args(&["bogusshell"]), &mut out));
    assert_eq!(code, 1);
    assert!(out.is_empty());
    assert!(chrome[0].contains("Unsupported shell: bogusshell"));
}
