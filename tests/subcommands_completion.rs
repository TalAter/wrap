#[test]
fn fish_emits_one_complete_line_per_flag_name() {
    let fx = Fixture::real();
    let script = generate_fish(&fx.registry(), "wrap");
    assert!(script.starts_with("# Generated by `wrap --completion fish`. Do not edit by hand.\n\ncomplete -c wrap -l log -d 'Show log entries'\n"));
    assert!(script.contains("\ncomplete -c wrap -l help -d 'Show this help'\ncomplete -c wrap -s h -d 'Show this help'\n"));
    assert!(script.contains("\ncomplete -c wrap -l model -x -a 'anthropic openai openrouter groq mistral ollama claude-code' -d 'Override LLM provider/model'\n"));
    assert!(script.contains("\ncomplete -c wrap -l completion -x -a 'zsh bash fish' -d 'Print shell completion script'\n"));
    assert!(script.contains("\ncomplete -c wrap -l verbose -d 'Enable debug output on stderr'\n"));
    let line_count = script
        .lines()
        .filter(|l| l.starts_with("complete -c wrap"))
        .count();
    assert_eq!(line_count, fx.all().map(|f| names(f).len()).sum::<usize>());
    let custom = generate_fish(&fx.registry(), "w");
    assert!(custom.contains("complete -c w ") && !custom.contains("complete -c wrap"));
}

