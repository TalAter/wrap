//! `--completion`: shell completion scripts generated from the registry so
//! every flag, alias and value completer stays in sync with the CLI.

use std::io::Write;
use std::sync::LazyLock;

use regex::Regex;

use crate::chrome::chrome;
use crate::config::providers::{API_PROVIDERS, CLI_PROVIDERS};

use super::registry::{self, CliFlag, CompletionKind, commands, options};

pub const SUPPORTED_SHELLS: [&str; 3] = ["zsh", "bash", "fish"];
const DEFAULT_EXECUTABLE_NAME: &str = "wrap";
const HINT: &str = "Run `wrap --help completion` for install instructions.";

// The name becomes `_<name>` shell function identifiers; bash is the
// strictest about those.
static EXECUTABLE_NAME: LazyLock<Regex> =
    LazyLock::new(|| Regex::new("^[A-Za-z_][A-Za-z0-9_]*$").unwrap());

pub fn flag() -> CliFlag {
    registry::command(
        "--completion",
        &["--completions"],
        "completion",
        "Print shell completion script",
        "w --completion <shell> [name]",
        Some(format!(
            "Supported shells: {}\n\nBy default the completion registers the command name `wrap`. Pass an optional\nsecond argument to register a different name (e.g. a shell alias).\n\nInstall (zsh):\n  wrap --completion zsh > ~/.local/share/zsh/site-functions/_wrap\n  (ensure the directory is on your $fpath, then run `compinit`)\n\nInstall (bash):\n  wrap --completion bash > ~/.local/share/bash-completion/completions/wrap\n\nInstall (fish):\n  wrap --completion fish > ~/.config/fish/completions/wrap.fish",
            SUPPORTED_SHELLS.join(", ")
        )),
        Some(CompletionKind::Shells),
    )
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Shell {
    Zsh,
    Bash,
    Fish,
}

impl Shell {
    fn parse(name: &str) -> Option<Shell> {
        match name {
            "zsh" => Some(Shell::Zsh),
            "bash" => Some(Shell::Bash),
            "fish" => Some(Shell::Fish),
            _ => None,
        }
    }
}

/// What the generators read: the flags to complete and the provider names
/// offered for `--model`.
pub struct Registry<'a> {
    pub commands: &'a [CliFlag],
    pub options: &'a [CliFlag],
    pub providers: &'a [String],
}

impl Registry<'_> {
    fn flags(&self) -> impl Iterator<Item = &CliFlag> {
        self.commands.iter().chain(self.options.iter())
    }

    fn names_with(&self, kind: CompletionKind) -> Vec<&str> {
        self.flags()
            .filter(|f| f.completion == Some(kind))
            .flat_map(CliFlag::names)
            .collect()
    }
}

/// API providers then CLI providers, in registry order.
pub fn provider_names() -> Vec<String> {
    API_PROVIDERS
        .iter()
        .map(|p| p.name.to_string())
        .chain(CLI_PROVIDERS.iter().map(|p| p.name.to_string()))
        .collect()
}

// An unescaped `]` ends the [description]; `\` and `'` break the
// single-quoted spec.
fn escape_zsh(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace(']', "\\]")
        .replace('\'', "'\\''")
}

pub fn generate_zsh(registry: &Registry, name: &str) -> String {
    let value_action = |flag: &CliFlag| match flag.completion {
        Some(CompletionKind::Providers) => format!(":provider:_{name}_providers"),
        Some(CompletionKind::Shells) => format!(":shell:({})", SUPPORTED_SHELLS.join(" ")),
        None => String::new(),
    };
    let mut specs = Vec::new();
    for flag in registry.flags() {
        let names: Vec<&str> = flag.names().collect();
        // Once one spelling is typed the others are hidden.
        let exclusion = if names.len() > 1 {
            format!("({})", names.join(" "))
        } else {
            String::new()
        };
        let value_prefix = if flag.takes_value() { "=" } else { "" };
        let suffix = format!(
            "{value_prefix}[{}]{}",
            escape_zsh(&flag.description),
            value_action(flag)
        );
        for flag_name in names {
            specs.push(format!("'{exclusion}{flag_name}{suffix}'"));
        }
    }
    let providers: Vec<String> = registry
        .providers
        .iter()
        .map(|p| format!("'{}'", escape_zsh(p)))
        .collect();

    format!(
        "#compdef {name}\n\
         # Generated by `{name} --completion zsh`. Do not edit by hand.\n\
         \n\
         _{name}_providers() {{\n\
         \x20 local -a providers=({})\n\
         \x20 compadd -S ':' -q -- \"${{providers[@]}}\"\n\
         }}\n\
         \n\
         _{name}() {{\n\
         \x20 _arguments -s \\\n\
         \x20   {}\n\
         }}\n\
         \n\
         _{name} \"$@\"\n",
        providers.join(" "),
        specs.join(" \\\n    ")
    )
}

pub fn generate_bash(registry: &Registry, name: &str) -> String {
    let all_names: Vec<&str> = registry.flags().flat_map(CliFlag::names).collect();
    // A trailing colon plus `compopt -o nospace` mirrors zsh's `-S ':' -q`:
    // tab gives `anthropic:` and the model is typed straight after it.
    let provider_words: Vec<String> = registry.providers.iter().map(|p| format!("{p}:")).collect();
    let provider_pattern = registry.names_with(CompletionKind::Providers).join("|");
    let shell_pattern = registry.names_with(CompletionKind::Shells).join("|");

    let mut arms = Vec::new();
    if !provider_pattern.is_empty() {
        arms.push(format!(
            "    {provider_pattern})\n      COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))\n      compopt -o nospace 2>/dev/null\n      return\n      ;;",
            provider_words.join(" ")
        ));
    }
    if !shell_pattern.is_empty() {
        arms.push(format!(
            "    {shell_pattern})\n      COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))\n      return\n      ;;",
            SUPPORTED_SHELLS.join(" ")
        ));
    }
    let case_block = if arms.is_empty() {
        String::new()
    } else {
        format!("  case \"$prev\" in\n{}\n  esac\n\n", arms.join("\n"))
    };

    format!(
        "# Generated by `{name} --completion bash`. Do not edit by hand.\n\
         \n\
         _{name}() {{\n\
         \x20 local cur prev\n\
         \x20 cur=\"${{COMP_WORDS[COMP_CWORD]}}\"\n\
         \x20 prev=\"${{COMP_WORDS[COMP_CWORD-1]}}\"\n\
         \n\
         {case_block}\x20 if [[ \"$cur\" == -* ]]; then\n\
         \x20   COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))\n\
         \x20 fi\n\
         }}\n\
         \n\
         complete -F _{name} {name}\n",
        all_names.join(" ")
    )
}

// Fish single-quoted strings only honor `\\` and `\'`.
fn escape_fish(s: &str) -> String {
    s.replace('\\', "\\\\").replace('\'', "\\'")
}

pub fn generate_fish(registry: &Registry, name: &str) -> String {
    let mut lines = vec![
        format!("# Generated by `{name} --completion fish`. Do not edit by hand."),
        String::new(),
    ];
    for flag in registry.flags() {
        for flag_name in flag.names() {
            let mut parts = vec!["complete".to_string(), "-c".to_string(), name.to_string()];
            if let Some(long) = flag_name.strip_prefix("--") {
                parts.push("-l".into());
                parts.push(long.into());
            } else if let Some(short) = flag_name.strip_prefix('-') {
                parts.push("-s".into());
                parts.push(short.into());
            }
            match flag.completion {
                Some(CompletionKind::Providers) => {
                    let providers: Vec<String> =
                        registry.providers.iter().map(|p| escape_fish(p)).collect();
                    parts.extend([
                        "-x".into(),
                        "-a".into(),
                        format!("'{}'", providers.join(" ")),
                    ]);
                }
                Some(CompletionKind::Shells) => {
                    parts.extend([
                        "-x".into(),
                        "-a".into(),
                        format!("'{}'", SUPPORTED_SHELLS.join(" ")),
                    ]);
                }
                None if flag.takes_value() => parts.push("-x".into()),
                None => {}
            }
            parts.push("-d".into());
            parts.push(format!("'{}'", escape_fish(&flag.description)));
            lines.push(parts.join(" "));
        }
    }
    format!("{}\n", lines.join("\n"))
}

pub fn generate(shell: Shell, registry: &Registry, name: &str) -> String {
    match shell {
        Shell::Zsh => generate_zsh(registry, name),
        Shell::Bash => generate_bash(registry, name),
        Shell::Fish => generate_fish(registry, name),
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CompletionRequest {
    pub shell: Shell,
    pub executable_name: String,
}

/// Validate `--completion` arguments: a supported shell and an optional
/// executable name usable as a shell function identifier.
pub fn run_completion(args: &[String]) -> Result<CompletionRequest, String> {
    let Some(shell_name) = args.first().filter(|s| !s.is_empty()) else {
        return Err(format!(
            "--completion requires a shell name ({}). {HINT}",
            SUPPORTED_SHELLS.join("/")
        ));
    };
    if args.len() > 2 {
        return Err(format!(
            "--completion takes at most two arguments (shell and optional name). {HINT}"
        ));
    }
    let Some(shell) = Shell::parse(shell_name) else {
        return Err(format!(
            "Unsupported shell: {shell_name}. Supported: {}. {HINT}",
            SUPPORTED_SHELLS.join(", ")
        ));
    };
    let executable_name = args
        .get(1)
        .cloned()
        .unwrap_or_else(|| DEFAULT_EXECUTABLE_NAME.to_string());
    if !EXECUTABLE_NAME.is_match(&executable_name) {
        return Err(format!(
            "Invalid executable name {}: the name is used as a shell function identifier, so it must start with a letter or underscore and contain only letters, digits, and underscores.",
            serde_json::to_string(&executable_name).unwrap_or_default()
        ));
    }
    Ok(CompletionRequest {
        shell,
        executable_name,
    })
}

pub fn run(args: &[String], out: &mut dyn Write) -> i32 {
    let request = match run_completion(args) {
        Ok(request) => request,
        Err(message) => {
            chrome(&message, None);
            return 1;
        }
    };
    let commands = commands();
    let options = options();
    let providers = provider_names();
    let registry = Registry {
        commands: &commands,
        options: &options,
        providers: &providers,
    };
    let script = generate(request.shell, &registry, &request.executable_name);
    let _ = out.write_all(script.as_bytes());
    0
}
