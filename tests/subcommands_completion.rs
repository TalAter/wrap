static CHROME_LOCK: Mutex<()> = Mutex::new(());

fn capture_chrome(f: impl FnOnce() -> i32) -> (i32, Vec<String>) {
    let _serial = CHROME_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let (tx, mut rx) = tokio::sync::mpsc::unbounded_channel();
    let guard = chrome::subscribe(tx);
    let code = f();
    drop(guard);
    let mut lines = Vec::new();
    while let Ok(n) = rx.try_recv() {
        if let Notification::Chrome { text, .. } = n {
            lines.push(text);
        }
    }
    (code, lines)
}

struct Fixture {
    commands: Vec<CliFlag>,
    options: Vec<CliFlag>,
    providers: Vec<String>,
}

impl Fixture {
    fn real() -> Fixture {
        Fixture {
            commands: commands(),
            options: options(),
            providers: provider_names(),
        }
    }

    fn registry(&self) -> Registry<'_> {
        Registry {
            commands: &self.commands,
            options: &self.options,
            providers: &self.providers,
        }
    }

    fn all(&self) -> impl Iterator<Item = &CliFlag> {
        self.commands.iter().chain(self.options.iter())
    }
}

fn cmd(flag: &str, description: &str, completion: Option<CompletionKind>) -> CliFlag {
    CliFlag {
        flag: flag.to_string(),
        aliases: vec![],
        id: flag.trim_start_matches('-').to_string(),
        description: description.to_string(),
        usage: format!("w {flag}"),
        help: None,
        completion,
        kind: FlagKind::Command,
    }
}

fn names(flag: &CliFlag) -> Vec<String> {
    std::iter::once(flag.flag.clone())
        .chain(flag.aliases.iter().cloned())
        .collect()
}

fn syntax_ok(bin: &str, flag: &str, script: &str) -> Option<bool> {
    let mut child = Command::new(bin)
        .arg(flag)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .ok()?;
    child
        .stdin
        .take()
        .unwrap()
        .write_all(script.as_bytes())
        .unwrap();
    let out = child.wait_with_output().unwrap();
    Some(out.status.success() && out.stderr.is_empty())
}

fn which(bin: &str) -> bool {
    Command::new("sh")
        .args(["-c", &format!("command -v {bin}")])
        .stdout(Stdio::null())
        .status()
        .is_ok_and(|s| s.success())
}

