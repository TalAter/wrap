#[test]
fn bash_script_defines_and_registers_the_function() {
    let fx = Fixture::real();
    let script = generate_bash(&fx.registry(), "wrap");
    assert!(script.starts_with("# Generated by `wrap --completion bash`. Do not edit by hand.\n\n_wrap() {\n  local cur prev\n  cur=\"${COMP_WORDS[COMP_CWORD]}\"\n  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n\n  case \"$prev\" in\n"));
    assert!(script.ends_with("\ncomplete -F _wrap wrap\n"));
    let custom = generate_bash(&fx.registry(), "w");
    assert!(custom.contains("_w()") && custom.contains("complete -F _w w"));
    assert!(!custom.contains("_wrap"));
}

#[test]
fn bash_case_arms_wire_providers_and_shells() {
    let fx = Fixture::real();
    let script = generate_bash(&fx.registry(), "wrap");
    assert!(script.contains("    --model|--provider)\n      COMPREPLY=($(compgen -W \"anthropic: openai: openrouter: groq: mistral: ollama: claude-code:\" -- \"$cur\"))\n      compopt -o nospace 2>/dev/null\n      return\n      ;;\n"));
    assert!(script.contains("    --completion|--completions)\n      COMPREPLY=($(compgen -W \"zsh bash fish\" -- \"$cur\"))\n      return\n      ;;\n  esac\n\n  if [[ \"$cur\" == -* ]]; then\n    COMPREPLY=($(compgen -W \""));
    let all: Vec<String> = fx.all().flat_map(names).collect();
    assert!(script.contains(&format!(
        "compgen -W \"{}\" -- \"$cur\"))\n  fi\n}}\n",
        all.join(" ")
    )));
}

