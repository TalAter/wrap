#!/usr/bin/env bash
# scripts/bump-tap.sh — bump talater/homebrew-wrap Formula/wrap.rb to a new
# tag: recompute sha256 for all four binary URLs (macOS arm/intel + Linux
# arm/intel) and open a PR. Replaces dawidd6/action-homebrew-bump-formula,
# whose brew-bump-pr backend only updates the first URL.
#
# Runs in CI with GH_TOKEN (PAT scoped to the tap) + TAG env set.
# Usage: TAG=v0.0.3 GH_TOKEN=… scripts/bump-tap.sh   (or scripts/bump-tap.sh v0.0.3)

set -euo pipefail

tag="${TAG:-${1:-}}"
case "$tag" in
  v*) ;;
  *) echo "Usage: TAG=v0.0.3 GH_TOKEN=… scripts/bump-tap.sh" >&2; exit 1 ;;
esac
version="${tag#v}"
repo="talater/wrap"
tap="talater/homebrew-wrap"
base="https://github.com/$repo"

sha256_of() {
  curl -fsSL "$1" | sha256sum | cut -d' ' -f1
}

echo "Computing sha256 for $tag…"
mac_arm_sha="$(sha256_of "$base/releases/download/$tag/wrap-aarch64-apple-darwin.tar.gz")"
mac_intel_sha="$(sha256_of "$base/releases/download/$tag/wrap-x86_64-apple-darwin.tar.gz")"
linux_arm_sha="$(sha256_of "$base/releases/download/$tag/wrap-aarch64-unknown-linux-gnu.tar.gz")"
linux_intel_sha="$(sha256_of "$base/releases/download/$tag/wrap-x86_64-unknown-linux-gnu.tar.gz")"

tap_dir="$(mktemp -d "${TMPDIR:-/tmp}/tap-XXXXXX")"
gh auth setup-git >/dev/null 2>&1
gh repo clone "$tap" "$tap_dir" -- --depth=1 >/dev/null 2>&1
git -C "$tap_dir" config user.name "github-actions[bot]"
git -C "$tap_dir" config user.email "41898282+github-actions[bot]@users.noreply.github.com"

branch="bump-wrap-$version"
git -C "$tap_dir" checkout -b "$branch"

formula="$tap_dir/Formula/wrap.rb"

# Each (url, sha256) pair is replaced atomically so a mid-run crash can't
# leave the formula half-bumped. Fails when a pair is missing from the formula.
bump_pair() {
  TRIPLE="$1" NEW_URL="$base/releases/download/$tag/wrap-$1.tar.gz" SHA="$2" FORMULA="$formula" \
    perl -0pi -e '
      my $re = qr{url "https://github\.com/talater/wrap/releases/download/v[^/]+/wrap-\Q$ENV{TRIPLE}\E\.tar\.gz"(\s+)sha256 "[a-f0-9]{64}"};
      s/$re/url "$ENV{NEW_URL}"${1}sha256 "$ENV{SHA}"/
        or die "Pattern not found in $ENV{FORMULA}: $ENV{TRIPLE}\n";
    ' "$formula"
}

bump_pair aarch64-apple-darwin       "$mac_arm_sha"
bump_pair x86_64-apple-darwin        "$mac_intel_sha"
bump_pair aarch64-unknown-linux-gnu  "$linux_arm_sha"
bump_pair x86_64-unknown-linux-gnu   "$linux_intel_sha"

git -C "$tap_dir" add Formula/wrap.rb
if [ -z "$(git -C "$tap_dir" diff --cached --name-only)" ]; then
  echo "Formula already at target version — nothing to do."
  exit 0
fi

git -C "$tap_dir" commit -m "wrap $version"
git -C "$tap_dir" push origin "$branch" --force-with-lease >/dev/null 2>&1

body="Auto-generated by the wrap release workflow.

Bumps wrap to $tag, recomputing sha256 for both macOS binaries and both Linux binaries."
existing="$(gh -R "$tap" pr list --head "$branch" --state open --json number -q '.[0].number' || true)"
if [ -n "$existing" ]; then
  echo "PR already open: $tap#$existing"
else
  gh -R "$tap" pr create --title "wrap $version" --body "$body" --head "$branch" --base main
fi
